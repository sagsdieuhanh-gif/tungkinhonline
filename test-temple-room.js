'use strict';
const assert=require('node:assert/strict');
const {createTempleRoom}=require('./temple-room');
let now=1000000;
const changes=[], room=createTempleRoom({now:()=>now,notify:(a,b)=>changes.push([a,b])});
const fakeReq={headers:{cookie:'','x-forwarded-proto':'https'},secure:true};
const fakeRes={headers:{},setHeader(k,v){this.headers[k]=v}};
const visitor=room.identity(fakeReq,fakeRes);
assert.ok(fakeRes.headers['Set-Cookie'].includes('HttpOnly'));
assert.equal(room.status(visitor).status,'new');
const joined=room.request({id:visitor.id,displayName:'Minh Tâm',comment:''});
assert.equal(joined.status,'approved');
assert.equal(room.status(visitor).status,'approved');
assert.equal(room.list().length,1);
assert.equal(room.moderation().pending.length,0);
assert.equal(room.approvedList().length,1);
assert.equal(room.request({id:'web:'+'e'.repeat(48),displayName:'Minh Tâm',comment:''}).reason,'name-in-use');
const tiktok=room.tiktokComment('tiktok-id','Diệu An','Nam mô');
assert.equal(tiktok.approved,true);
assert.equal(room.list().length,2);
assert.equal(room.submit(visitor.id,'ignored','Xin chào','web').ok,true);
assert.equal(room.submit(visitor.id,'ignored','spam','web').reason,'cooldown');
let messages=room.chat(visitor.id).messages;
assert.equal(messages.length,2);
assert.match(messages[1].text,/^Chúc Minh Tâm /);
assert.equal(messages[1].role,'abbot');
now+=5000;
assert.equal(room.submit('tt:tiktok-id','Diệu An','Niệm Phật','tiktok').ok,true);
messages=room.chat(visitor.id).messages;
assert.equal(messages.length,4);
assert.match(messages[3].text,/^Chúc Diệu An /);
assert.notEqual(messages[1].text,messages[3].text);
assert.equal(room.submitAbbot('Trụ trì chào mọi người').ok,true);
assert.equal(room.chat(visitor.id).messages.length,5);
assert.equal(room.chat(visitor.id).messages[4].automated,undefined);
assert.equal(room.setMute('tt:tiktok-id',true),true);
assert.equal(room.submit('tt:tiktok-id','Diệu An','spam','tiktok').reason,'muted');
assert.equal(room.remove('tt:tiktok-id'),true);
const full=createTempleRoom({now:()=>now,capacity:1});
assert.equal(full.request({id:'tt:1',displayName:'Phật tử 1'}).status,'approved');
assert.equal(full.request({id:'tt:2',displayName:'Phật tử 2'}).reason,'full');
now+=3*60000;room.sweep();
assert.equal(room.status(visitor).status,'new'); // attendance expires, name record stays
assert.equal(room.request({id:visitor.id,displayName:'Minh Tâm'}).status,'approved');
console.log('PASS open-door immediate join, no waiting, capacity, remembered name, blessings and mute');
