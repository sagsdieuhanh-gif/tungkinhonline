'use strict';
const assert=require('node:assert/strict');
const {createLuckyPool,PRICES}=require('./temple-loc');
let now=5000;
const pool=createLuckyPool({randomInt:(min,max)=>min,now:()=>now});
assert.equal(pool.view(),null);
assert.equal(pool.open(-2).ok,false);
assert.equal(pool.open(300).ok,true);
assert.equal(pool.open(100).ok,false);
assert.equal(pool.claim('abc').amount,1);
assert.equal(pool.claim('abc').ok,false);
assert.equal(pool.claim('xyz').amount,1);
assert.equal(pool.view().remaining,298);
assert.equal(pool.spend('abc','incense',()=>{}).ok,false);
let evs=0;
assert.equal(pool.spend('abc','bow',()=>{evs++;return {a:1}}).ok,true);
assert.equal(pool.balance('abc'),1);
assert.equal(pool.spend('abc','bow',()=>{evs++}).ok,false);
now+=1500;
assert.equal(pool.spend('abc','woodenFish',()=>{evs++}).ok,true);
assert.equal(pool.balance('abc'),0);
now+=1500;
assert.equal(pool.spend('abc','bow',()=>{throw Error('test failure')}).ok,false);
assert.equal(pool.balance('abc'),0);
assert.equal(pool.close().ok,true);
assert.equal(pool.claim('new').ok,false);
assert.equal(pool.open(15).ok,true);
assert.equal(pool.claim('abc').ok,true);
assert.equal(pool.status('abc').claimed,true);
assert.ok(PRICES.lotus===20&&PRICES.bow===0);
console.log('PASS lucky pool: random bounded award, no duplicate, fund cap, spending, close/new round');
